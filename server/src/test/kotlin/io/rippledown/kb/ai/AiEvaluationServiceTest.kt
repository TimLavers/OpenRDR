package io.rippledown.kb.ai

import io.kotest.matchers.nulls.shouldBeNull
import io.kotest.matchers.shouldBe
import io.kotest.matchers.types.shouldBeInstanceOf
import io.mockk.every
import io.mockk.mockk
import io.rippledown.model.Attribute
import io.rippledown.model.rule.AiBoolean
import io.rippledown.model.rule.AiEvaluationProfile
import io.rippledown.model.rule.evaluation.AiEvaluationRecord
import io.rippledown.model.rule.evaluation.AiEvaluationRequest
import io.rippledown.model.rule.evaluation.AiEvaluationResult
import io.rippledown.model.rule.evaluation.key
import io.rippledown.persistence.AiEvaluationStore
import io.rippledown.persistence.inmemory.InMemoryAiEvaluationStore
import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.async
import kotlinx.coroutines.delay
import kotlinx.coroutines.test.TestScope
import kotlinx.coroutines.test.runTest
import kotlinx.coroutines.withTimeout
import kotlinx.coroutines.yield
import kotlin.test.Test

internal class AiEvaluationServiceTest {
    private val notes = Attribute(1, "clinical_notes")
    private val hasDiabetes = AiBoolean(
        sourceAttribute = notes,
        instructions = "True if the notes affirm a personal history of diabetes.",
        revision = "rev-1",
        evaluationProfile = AiEvaluationProfile("gemini", "gemini-2.5-flash", 0.0, 1, 1)
    )
    private val request = AiEvaluationRequest(hasDiabetes, "T2 Diab")
    private val store = InMemoryAiEvaluationStore()
    private var now = 1_700_000_000_000L

    private class ScriptedClassifier(private val script: suspend (AiEvaluationRequest) -> AiClassification) : AiBooleanClassifier {
        var calls = 0
        override suspend fun classify(request: AiEvaluationRequest): AiClassification {
            calls++
            return script(request)
        }
    }

    private fun classified(value: Boolean, evidence: String? = null, model: String? = "gemini-2.5-flash-001") =
        AiClassification.Classified(value, evidence, model)

    private fun TestScope.service(
        classifier: AiBooleanClassifier,
        store: AiEvaluationStore = this@AiEvaluationServiceTest.store,
        cooldownMillis: Long = 10_000
    ) = AiEvaluationService(
        store = store,
        classifier = classifier,
        clock = { now },
        failureCooldownMillis = cooldownMillis,
        scope = backgroundScope
    )

    @Test
    fun `a classification is persisted before it is returned`() = runTest {
        // Given a classifier that answers true
        val classifier = ScriptedClassifier { classified(true, "T2 Diab") }
        val service = service(classifier)

        // When the request is evaluated
        val result = service.evaluate(request)

        // Then the result is the stored record's result and carries the record's metadata
        val record = store.recordFor(request.key())
        record shouldBe AiEvaluationRecord(
            key = request.key(),
            value = true,
            evidence = "T2 Diab",
            definition = hasDiabetes,
            evaluatedAt = now,
            requestedModel = "gemini-2.5-flash",
            reportedModel = "gemini-2.5-flash-001"
        )
        result shouldBe AiEvaluationResult.Success(true, "T2 Diab", now, "gemini-2.5-flash-001")
    }

    @Test
    fun `a stored record is used without calling the classifier`() = runTest {
        // Given a record already stored
        store.insertIfAbsent(
            AiEvaluationRecord(request.key(), false, null, hasDiabetes, 1L, "gemini-2.5-flash", null)
        )
        val classifier = ScriptedClassifier { error("Should not be called") }

        // When the request is evaluated
        val result = service(classifier).evaluate(request)

        // Then the stored result is returned and the classifier is not consulted
        result shouldBe AiEvaluationResult.Success(false, null, 1L, "gemini-2.5-flash")
        classifier.calls shouldBe 0
    }

    @Test
    fun `a stored record is not regenerated by a later request`() = runTest {
        // Given the request has been evaluated once
        val classifier = ScriptedClassifier { classified(true) }
        val service = service(classifier)
        service.evaluate(request)

        // When it is evaluated again later
        now += 60_000
        val again = service.evaluate(request)

        // Then the first result stands and no new classification is made
        again.shouldBeInstanceOf<AiEvaluationResult.Success>().evaluatedAt shouldBe now - 60_000
        classifier.calls shouldBe 1
    }

    @Test
    fun `concurrent requests for the same evaluation share one classification`() = runTest {
        // Given a classifier that blocks until released
        val gate = CompletableDeferred<Unit>()
        val classifier = ScriptedClassifier { gate.await(); classified(true) }
        val service = service(classifier)

        // When two callers request the same evaluation before the first completes
        val first = async { service.evaluate(request) }
        val second = async { service.evaluate(request) }
        yield()
        gate.complete(Unit)

        // Then both receive the same result from one classifier call
        first.await() shouldBe second.await()
        classifier.calls shouldBe 1
    }

    @Test
    fun `cancelling one waiter does not cancel the result another needs`() = runTest {
        // Given a classification in progress with two waiters
        val gate = CompletableDeferred<Unit>()
        val classifier = ScriptedClassifier { gate.await(); classified(true) }
        val service = service(classifier)
        val cancelled = async { service.evaluate(request) }
        val kept = async { service.evaluate(request) }
        yield()

        // When one waiter is cancelled and the classification then completes
        cancelled.cancel()
        gate.complete(Unit)

        // Then the other waiter receives the result and it was persisted
        kept.await().shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe true
        store.recordFor(request.key())?.value shouldBe true
        classifier.calls shouldBe 1
    }

    @Test
    fun `a classification failure is returned as a failure and nothing is stored`() = runTest {
        val classifier = ScriptedClassifier { AiClassification.Failed("Gemini unavailable") }

        val result = service(classifier).evaluate(request)

        result shouldBe AiEvaluationResult.Failure("Gemini unavailable")
        store.recordFor(request.key()).shouldBeNull()
    }

    @Test
    fun `a classifier exception is a failure, not a value, and the in-flight entry is released`() = runTest {
        // Given a classifier that throws once and then succeeds
        var first = true
        val classifier = ScriptedClassifier {
            if (first) {
                first = false
                throw IllegalStateException("boom")
            }
            classified(true)
        }
        val service = service(classifier, cooldownMillis = 0)

        // When the request is evaluated twice
        val failed = service.evaluate(request)
        val succeeded = service.evaluate(request)

        // Then the first is a failure naming the problem and the second is a fresh, successful classification
        failed shouldBe AiEvaluationResult.Failure("boom")
        succeeded.shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe true
        classifier.calls shouldBe 2
    }

    @Test
    fun `a classifier exception without a message is named by its type`() = runTest {
        val classifier = ScriptedClassifier { throw NullPointerException() }

        val result = service(classifier).evaluate(request)

        result shouldBe AiEvaluationResult.Failure("java.lang.NullPointerException")
    }

    @Test
    fun `a classifier timeout is a failure and the in-flight entry is released`() = runTest {
        // Given a classifier whose own deadline expires
        var first = true
        val classifier = ScriptedClassifier {
            if (first) {
                first = false
                withTimeout(10) { delay(1_000) }
            }
            classified(false)
        }
        val service = service(classifier, cooldownMillis = 0)

        // When the request is evaluated and then retried
        val failed = service.evaluate(request)
        val succeeded = service.evaluate(request)

        // Then the timeout is a failure and the retry runs a fresh classification
        failed.shouldBeInstanceOf<AiEvaluationResult.Failure>()
        succeeded.shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe false
        classifier.calls shouldBe 2
    }

    @Test
    fun `a failure is memoised within the cooldown`() = runTest {
        // Given a classifier that fails
        val classifier = ScriptedClassifier { AiClassification.Failed("rate limited") }
        val service = service(classifier, cooldownMillis = 10_000)

        // When the request is evaluated repeatedly within the cooldown
        service.evaluate(request)
        now += 5_000
        val second = service.evaluate(request)

        // Then the memoised failure is returned without another provider call
        second shouldBe AiEvaluationResult.Failure("rate limited")
        classifier.calls shouldBe 1
    }

    @Test
    fun `after the cooldown a request classifies again`() = runTest {
        var attempts = 0
        val classifier = ScriptedClassifier {
            attempts++
            if (attempts == 1) AiClassification.Failed("rate limited") else classified(true)
        }
        val service = service(classifier, cooldownMillis = 10_000)

        service.evaluate(request)
        now += 10_000
        val result = service.evaluate(request)

        result.shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe true
        classifier.calls shouldBe 2
    }

    @Test
    fun `an explicit retry ignores the cooldown`() = runTest {
        var attempts = 0
        val classifier = ScriptedClassifier {
            attempts++
            if (attempts == 1) AiClassification.Failed("rate limited") else classified(true)
        }
        val service = service(classifier, cooldownMillis = 10_000)

        service.evaluate(request)
        val result = service.evaluate(request, retryAfterFailure = true)

        result.shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe true
        classifier.calls shouldBe 2
    }

    @Test
    fun `a failure for one input does not affect another`() = runTest {
        val classifier = ScriptedClassifier { if (it.input == "T2 Diab") AiClassification.Failed("x") else classified(false) }
        val service = service(classifier)

        service.evaluate(request)
        val other = service.evaluate(AiEvaluationRequest(hasDiabetes, "FH diab"))

        other.shouldBeInstanceOf<AiEvaluationResult.Success>().value shouldBe false
    }

    @Test
    fun `a racing duplicate written by someone else wins`() = runTest {
        // Given another server stored a record for this key while our classification was in progress
        val classifier = ScriptedClassifier {
            store.insertIfAbsent(AiEvaluationRecord(request.key(), false, null, hasDiabetes, 5L, "gemini-2.5-flash", null))
            classified(true, "T2 Diab")
        }

        // When our classification completes
        val result = service(classifier).evaluate(request)

        // Then the stored record is the result everyone uses, not our classification
        result shouldBe AiEvaluationResult.Success(false, null, 5L, "gemini-2.5-flash")
    }

    @Test
    fun `a persistence failure makes the evaluation a failure, never a value`() = runTest {
        // Given a store that cannot write
        val failing = mockk<AiEvaluationStore>()
        every { failing.recordFor(any()) } returns null
        every { failing.insertIfAbsent(any()) } throws IllegalStateException("connection lost")
        val classifier = ScriptedClassifier { classified(true) }

        // When the request is evaluated
        val result = service(classifier, store = failing).evaluate(request)

        // Then the result is an explicit failure
        result shouldBe AiEvaluationResult.Failure("The evaluation could not be saved: connection lost")
    }

    @Test
    fun `a store read failure is explicit`() = runTest {
        val failing = mockk<AiEvaluationStore>()
        every { failing.recordFor(any()) } throws IllegalStateException("connection lost")
        val classifier = ScriptedClassifier { error("Should not be called") }

        val result = service(classifier, store = failing).evaluate(request)

        result shouldBe AiEvaluationResult.Failure("Saved evaluations could not be read: connection lost")
        classifier.calls shouldBe 0
    }
}
